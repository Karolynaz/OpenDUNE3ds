void String_LoadLithuanian(uint16 *offsets, char *buffer, uint32 bufferSize, uint16 *countOut)
{
	uint32 pos = 0;

	for (uint16 i = 0; i < STRINGS_LT_COUNT; i++) {
		const char *s = s_stringsLT[i];
		size_t len = strlen(s);
		if (pos + len + 1 >= bufferSize) break;
		offsets[i] = (uint16)pos;
		memcpy(buffer + pos, s, len + 1);
		pos += (uint32)(len + 1);
	}
	offsets[STRINGS_LT_COUNT] = (uint16)pos;
	if (countOut != NULL) *countOut = STRINGS_LT_COUNT;
}

