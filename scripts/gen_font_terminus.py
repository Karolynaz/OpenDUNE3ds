"""Extract unscaled Terminus Bold 14 glyphs; source and OFL in assets/fonts."""
from pathlib import Path
import re
root = Path(__file__).resolve().parent.parent
source = (root / 'assets/fonts/ter-u14b.bdf').read_text()
chars = list(range(32,127)) + list(map(ord, 'ĄąČčĘęĖėĮįŠšŲųŪūŽž'))
glyphs = {}
for block in source.split('STARTCHAR ')[1:]:
    code = int(re.search(r'ENCODING (\d+)',block)[1])
    if code in chars:
        glyphs[code] = [int(x,16) for x in block.split('BITMAP\n')[1].split('ENDCHAR')[0].split()]
out = ['/* Terminus Bold 14, Copyright Dimitar Toshkov Zhekov. SIL OFL 1.1.',
       ' * Generated by scripts/gen_font_terminus.py. See assets/fonts/Terminus-OFL.txt. */',
       '#ifndef FONT_TERMINUS_H', '#define FONT_TERMINUS_H',
       'static const unsigned char s_terminusRows[][14] = {']
for code in chars:
    assert len(glyphs[code]) == 14
    out.append('    {'+', '.join(hex(x) for x in glyphs[code])+'},')
out += ['};', '#endif']
(root / 'src/gui/font_terminus.h').write_text('\n'.join(out)+'\n')
