#!/usr/bin/env python3
"""Regenerates src/gui/shop_art_3ds.h from the purchase-window background PNGs.

The PNGs in scripts/shop_art/ are pixel-art mock-ups (400x240 top, 320x240 bottom).
Every pixel is stored as an index into the stock Dune II IBM.PAL palette, so the
game draws the backgrounds with its own palette (UI mask 0).

Usage: python3 scripts/gen_shop_art.py [path/to/DUNE.PAK]
"""
import os, struct, sys, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PAK = sys.argv[1] if len(sys.argv) > 1 else "/Users/karolynaz/Library/Application Support/Azahar/sdmc/3ds/dune3ds/DUNE.PAK"


def read_png(path):
    d = open(path, "rb").read(); p = 8; idat = b""; ct = 2
    while p < len(d):
        l = struct.unpack(">I", d[p:p + 4])[0]; t = d[p + 4:p + 8]; c = d[p + 8:p + 8 + l]; p += 12 + l
        if t == b"IHDR": w, h, _, ct = struct.unpack(">IIBB", c[:10])
        elif t == b"IDAT": idat += c
    raw = zlib.decompress(idat); bpp = {2: 3, 6: 4}[ct]; s = w * bpp; prev = bytearray(s); rows = []; i = 0
    for _ in range(h):
        f = raw[i]; i += 1; cur = bytearray(raw[i:i + s]); i += s
        for x in range(s):
            a = cur[x - bpp] if x >= bpp else 0; b = prev[x]; c2 = prev[x - bpp] if x >= bpp else 0
            if f == 1: cur[x] = (cur[x] + a) & 255
            elif f == 2: cur[x] = (cur[x] + b) & 255
            elif f == 3: cur[x] = (cur[x] + ((a + b) >> 1)) & 255
            elif f == 4:
                pp = a + b - c2; pa, pb, pc = abs(pp - a), abs(pp - b), abs(pp - c2)
                cur[x] = (cur[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c2)) & 255
        prev = cur; rows.append([tuple(cur[k * bpp:k * bpp + 3]) for k in range(w)])
    return w, h, rows


def read_pak(path):
    files = {}; data = open(path, "rb").read(); pos = 0
    nxt = struct.unpack_from("<I", data, pos)[0]; pos += 4
    while nxt:
        cur = nxt; e = data.index(b"\0", pos); name = data[pos:e].decode("ascii", "ignore").upper(); pos = e + 1
        nxt = struct.unpack_from("<I", data, pos)[0]; pos += 4
        files[name] = data[cur:(nxt if nxt else len(data))]
    return files


pal_raw = read_pak(PAK)["IBM.PAL"]
pal = [tuple((pal_raw[i * 3 + k] * 255) // 63 for k in range(3)) for i in range(256)]
lookup = {}
for idx in range(251):                      # 251..255 are animated by the engine
    lookup.setdefault(pal[idx], idx)


def indices(path, w_expected, h_expected):
    w, h, rows = read_png(path)
    assert (w, h) == (w_expected, h_expected), (path, w, h)
    out = bytearray()
    for r in rows:
        for px in r:
            if px not in lookup:
                raise SystemExit("colour %s of %s is not in IBM.PAL" % (px, path))
            out.append(lookup[px])
    return out


def emit(name, data):
    lines = []
    for i in range(0, len(data), 40):
        lines.append(",".join(str(v) for v in data[i:i + 40]))
    return "static const unsigned char %s[%d] = {\n%s\n};\n\n" % (name, len(data), ",\n".join(lines))


top = indices(os.path.join(HERE, "shop_art", "shop_top_400x240.png"), 400, 240)
bot = indices(os.path.join(HERE, "shop_art", "shop_bottom_320x240.png"), 320, 240)
with open(os.path.join(ROOT, "src", "gui", "shop_art_3ds.h"), "w") as f:
    f.write("/* GENERATED by scripts/gen_shop_art.py - do not edit.\n"
            " * Purchase window backgrounds as stock Dune II (IBM.PAL) palette indices. */\n"
            "#ifndef SHOP_ART_3DS_H\n#define SHOP_ART_3DS_H\n\n")
    f.write(emit("s_shopTopBG", top))
    f.write(emit("s_shopBotBG", bot))
    f.write("#endif\n")
print("wrote src/gui/shop_art_3ds.h")
