#!/usr/bin/python3
"""Generate src/gui/font_cairo.h from Cairopixel-G3DeP.ttf (1-bit glyphs at 25px).

Usage: /usr/bin/python3 scripts/gen_font_cairo.py /path/to/Cairopixel-G3DeP.ttf
Needs Pillow. Glyphs are rendered with FreeType's monochrome rasteriser so every
pixel is fully on/off (the console uses a paletted framebuffer, no alpha).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZE = 25            # Figma font size
TRACKING = 1.25      # Figma letter spacing (5%)
LINE_HEIGHT = 20     # Figma line height
LT = "ĄąČčĘęĖėĮįŠšŲųŪūŽž"
CHARS = [chr(c) for c in range(32, 127)] + list(LT)

font_path = sys.argv[1]
font = ImageFont.truetype(font_path, SIZE)
BASE = 40

glyphs, rows_out = [], []
for ch in CHARS:
    im = Image.new("1", (64, 64), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((8, BASE), ch, font=font, fill=1, anchor="ls")
    bbox = im.getbbox()
    adv4 = int(round((font.getlength(ch) + TRACKING) * 4))
    if bbox is None:
        glyphs.append((adv4, 0, 0, 0, 0, len(rows_out)))
        continue
    x0, y0, x1, y1 = bbox
    w, h = x1 - x0, y1 - y0
    assert w <= 32, (ch, w)
    off = len(rows_out)
    for y in range(y0, y1):
        v = 0
        for x in range(x0, x1):
            if im.getpixel((x, y)):
                v |= 1 << (w - 1 - (x - x0))
        rows_out.append(v)
    glyphs.append((adv4, x0 - 8, BASE - y0, w, h, off))

cap = max(g[2] for g, c in zip(glyphs, CHARS) if c == "H")
lines = []
lines.append("/* Generated by scripts/gen_font_cairo.py from Cairopixel-G3DeP.ttf (%dpx, 1-bit). Do not edit. */" % SIZE)
lines.append("#ifndef FONT_CAIRO_H\n#define FONT_CAIRO_H")
lines.append("#include <stdint.h>")
lines.append("#define CAIRO_LINE_H %d" % LINE_HEIGHT)
lines.append("#define CAIRO_CAP_H %d" % cap)
lines.append("#define CAIRO_ASCII_COUNT 95")
lines.append("typedef struct { uint16_t adv4; int8_t xoff; int8_t top; uint8_t w, h; uint16_t off; } CairoGlyph;")
lines.append("static const uint32_t s_cairoRows[%d] = {" % len(rows_out))
for i in range(0, len(rows_out), 8):
    lines.append("    " + ", ".join("0x%X" % v for v in rows_out[i:i + 8]) + ",")
lines.append("};")
lines.append("static const CairoGlyph s_cairoGlyphs[%d] = {" % len(glyphs))
for ch, g in zip(CHARS, glyphs):
    name = ch if ch.isascii() and ch not in "\\'*/" else "U+%04X" % ord(ch)
    lines.append("    /* %s */ { %d, %d, %d, %d, %d, %d }," % ((name,) + g))
lines.append("};")
lines.append("#endif")
open("src/gui/font_cairo.h", "w").write("\n".join(lines) + "\n")
print("glyphs", len(glyphs), "rows", len(rows_out), "cap", cap)
